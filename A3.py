# Resistor band color
color = input("Enter band color: ").lower()
n = color.lower()

if n == "black":
    print("Digit = 0")
elif n == "brown":
    print("Digit = 1")
elif n == "red":
    print("Digit = 2")
elif n == "orange":
    print("Digit = 3")
elif n == "yellow":
    print("Digit = 4")
elif n == "green":
    print("Digit = 5")
elif n == "blue":
    print("Digit = 6")
elif n == "violet":
    print("Digit = 7")
elif n == "grey":
    print("Digit = 8")
elif n == "white":
    print("Digit = 9")
else:
    print("Invalid color")